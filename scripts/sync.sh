#!/usr/bin/env bash
set -euo pipefail

# Sync commands (and rules where applicable) to Codex and Cursor locally.
# Usage: ./scripts/sync.sh [--remote user@host]
# --remote also syncs to the supplied SSH destination.

script_dir="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
repo_dir="$(cd -- "$script_dir/.." && pwd)"
remote=""

while [[ $# -gt 0 ]]; do
    case "$1" in
        --remote)
            if [[ $# -lt 2 || -z "$2" || "$2" == -* ]]; then
                printf 'Usage: ./scripts/sync.sh [--remote user@host]\n' >&2
                exit 1
            fi
            remote="$2"
            shift 2
            ;;
        *) printf 'Unknown option: %s\n' "$1" >&2; exit 1 ;;
    esac
done

# --- Codex: commands go to prompts/, rules flatten to AGENTS.md -------------

codex_dir="${CODEX_HOME:-$HOME/.codex}"
codex_prompts="$codex_dir/prompts"

generated_agents="$(mktemp)"
trap 'rm -f -- "$generated_agents"' EXIT
python3 "$script_dir/generate-agents.py" > "$generated_agents"

# Only replace files owned by this generator; preserve handwritten instructions.
check_agents_guard() {
    local dir="$1"
    if [[ -e "$dir/AGENTS.md" || -L "$dir/AGENTS.md" ]]; then
        if [[ -L "$dir/AGENTS.md" ]] || ! head -n 1 -- "$dir/AGENTS.md" | cmp -s - <(head -n 1 -- "$generated_agents"); then
            printf 'Refusing to overwrite unmanaged %s/AGENTS.md.\n' "$dir" >&2
            return 1
        fi
    fi
}

check_agents_guard "$codex_dir"

mkdir -p -- "$codex_prompts"
cp -- "$repo_dir"/commands/*.md "$codex_prompts/"
cp -- "$generated_agents" "$codex_dir/AGENTS.md"

printf 'Synced commands + rules to %s.\n' "$codex_dir"

# --- Cursor: commands go to commands/ (no AGENTS.md) ------------------------

cursor_dir="${CURSOR_HOME:-$HOME/.cursor}"
cursor_commands="$cursor_dir/commands"

mkdir -p -- "$cursor_commands"
cp -- "$repo_dir"/commands/*.md "$cursor_commands/"

printf 'Synced commands to %s.\n' "$cursor_dir"

# --- Remote -----------------------------------------------------------------

if [[ -n "$remote" ]]; then
    ssh -- "$remote" "$(cat <<'REMOTE_GUARD'
    dir=~/.codex
    if [ -e "$dir/AGENTS.md" ] || [ -L "$dir/AGENTS.md" ]; then
        if [ -L "$dir/AGENTS.md" ] || [ "$(head -n 1 "$dir/AGENTS.md")" != "<!-- Generated by ai-agent-config/generate-agents.py; DO NOT EDIT. -->" ]; then
            echo "Refusing to overwrite unmanaged $dir/AGENTS.md." >&2
            exit 1
        fi
    fi
    mkdir -p -- ~/.codex/prompts ~/.cursor/commands
REMOTE_GUARD
)"

    rsync -a -- "$repo_dir"/commands/*.md "$remote:~/.codex/prompts/"
    rsync -a -- "$generated_agents"          "$remote:~/.codex/AGENTS.md"
    rsync -a -- "$repo_dir"/commands/*.md "$remote:~/.cursor/commands/"

    printf 'Synced to %s.\n' "$remote"
fi
printf 'Restart Codex/Cursor and start a new chat to pick up changes.\n'
