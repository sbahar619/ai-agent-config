#!/usr/bin/env python3
"""Generate Codex instructions from rules/*.mdc on stdout; do not install them."""

import re
import sys
from pathlib import Path


def unquote(value):
    value = value.strip()
    if len(value) >= 2 and value[0] == value[-1] and value[0] in "\"'":
        return value[1:-1]
    return value


def render_rule(path):
    text = path.read_text()
    match = re.match(r"\A---\n(.*?)\n---\n(.*)\Z", text, re.DOTALL)
    if not match:
        raise ValueError(f"{path.name}: missing or invalid frontmatter")
    header, body = match.groups()
    fields = {}
    globs = []
    in_globs = False
    # Support this repository's scalar fields and block-list globs.
    for line in header.splitlines():
        if not line.strip():
            continue
        if in_globs and line.startswith("  - "):
            globs.append(unquote(line[4:]))
            continue
        key, separator, value = line.partition(":")
        if not separator or key not in {"description", "globs", "alwaysApply"}:
            raise ValueError(f"{path.name}: unsupported frontmatter: {line}")
        value = value.strip()
        in_globs = key == "globs" and not value
        if key == "globs":
            if value.startswith(("[", "{", "|", ">")):
                raise ValueError(f"{path.name}: use a scalar or block list for globs")
            if value:
                globs.append(unquote(value))
        else:
            fields[key] = unquote(value)
    description = fields.get("description", "")
    always_apply = fields.get("alwaysApply", "false")
    if always_apply not in {"true", "false"}:
        raise ValueError(f"{path.name}: alwaysApply must be true or false")
    if not body.strip() or (not description and not globs and always_apply != "true"):
        raise ValueError(f"{path.name}: rule needs a body and an explicit scope")

    if always_apply == "true":
        scope = "Apply to every task."
    elif globs:
        patterns = ", ".join(f"`{pattern}`" for pattern in globs)
        scope = f"File scope: {patterns}."
    else:
        scope = f"Task scope: {description}"
    if description and (always_apply == "true" or globs):
        scope += f"\nPurpose: {description}"

    # Use the rule name as the sole title; preserve names used by cross-references.
    body_lines = body.strip().splitlines()
    if body_lines[0].startswith("# "):
        body_lines = body_lines[1:]
    lines = []
    fence = None
    for line in body_lines:
        stripped = line.lstrip()
        if stripped.startswith(("```", "~~~")):
            marker = stripped[:3]
            fence = None if fence == marker else marker if fence is None else fence
        if fence is None and re.match(r"#{1,5} ", line):
            line = "#" + line
        lines.append(line)
    return f"## {path.stem}\n\n{scope}\n\n" + "\n".join(lines).strip()


def main():
    paths = sorted((Path(__file__).resolve().parent.parent / "rules").glob("*.mdc"))
    if not paths:
        raise ValueError("No rules/*.mdc files found")
    sections = [render_rule(path) for path in paths]
    # Keep the ownership marker stable for previously synced instruction files.
    print("<!-- Generated by ai-agent-config/generate-agents.py; DO NOT EDIT. -->")
    print("Apply the following shared rules only within their stated scopes.\n")
    print("File patterns describe applicability; they do not conditionally load sections.\n")
    print("\n\n".join(sections))


if __name__ == "__main__":
    try:
        main()
    except (OSError, ValueError) as error:
        sys.exit(str(error))
